// Helper to normalize strings for comparison
export function cleanForCompare(str) {
  if (!str) return '';
  return str
    .toLowerCase()
    .replace(/[.,\/#!$%\^&\*;:{}=\-_`~()?"'’]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * DOL English Exact Masking Generator
 * Compares user text with target text word by word.
 * - Words typed correctly are revealed in green.
 * - Unmatched or remaining words are masked with asterisks matching their exact character length.
 * - Punctuation marks (commas, question marks, exclamation marks) are kept intact.
 */
export function generateDolMaskedHint(targetSentence, userTypedText, isEasyMode = true) {
  if (!targetSentence) return { parts: [], isFullyCorrect: false };

  // Split target into tokens (preserving words and punctuation)
  const tokens = targetSentence.match(/[\w']+|[^\s\w]/g) || [];
  const userWords = cleanForCompare(userTypedText).split(' ').filter(Boolean);

  let wordIndex = 0;
  let matchesCount = 0;
  let totalWordCount = 0;

  const parts = tokens.map((token) => {
    const isPunctuation = /^[^\w\s]$/.test(token);

    if (isPunctuation) {
      return {
        text: token,
        type: 'punctuation',
        isPunctuation: true,
        isCorrect: true
      };
    }

    // It's a word
    const currentWordIndex = wordIndex++;
    totalWordCount++;

    const cleanToken = cleanForCompare(token);
    const userWord = userWords[currentWordIndex] || '';

    const isMatch = userWord.length > 0 && userWord === cleanToken;

    if (isMatch) {
      matchesCount++;
      return {
        text: token,
        type: 'word',
        isCorrect: true,
        isMasked: false
      };
    }

    // Not matched yet -> Mask with asterisks
    const maskedLength = Math.max(1, token.length);
    const maskedString = '*'.repeat(maskedLength);

    return {
      text: maskedString,
      originalText: token,
      type: 'word',
      isCorrect: false,
      isMasked: true
    };
  });

  const isFullyCorrect = totalWordCount > 0 && matchesCount === totalWordCount;

  return {
    parts,
    isFullyCorrect,
    matchesCount,
    totalWordCount
  };
}
